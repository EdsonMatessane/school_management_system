CREATE TABLE IF NOT EXISTS system_statuses (
    id BIGSERIAL PRIMARY KEY,
    module VARCHAR(40) NOT NULL,
    code VARCHAR(60) NOT NULL,
    label VARCHAR(120) NOT NULL,
    tone VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (tone IN ('pending', 'paid', 'rejected', 'neutral')),
    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    system_defined BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_system_statuses_module_code UNIQUE (module, code)
);

CREATE INDEX IF NOT EXISTS idx_system_statuses_module_order
    ON system_statuses (module, sort_order, id);

